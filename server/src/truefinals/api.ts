import createClient, { Client } from 'openapi-fetch';
import type { paths } from './truefinals-schema'; // generated by openapi-typescript
import pThrottle from 'p-throttle';

class TrueFinals {
	apiKey: string;
	userId: string;
	client: Client<paths, `${string}/${string}`>;

	tournaments: string[];
	activeTournament: string;

	constructor(userId: string, userKey: string) {
		this.userId = userId;
		this.apiKey = userKey;

		const client = createClient<paths>({ baseUrl: 'https://truefinals.com/api/' });
		this.client = client;

		this.tournaments = process.env.TF_TOURNAMENT_IDS.split(',').map((id) => id.trim());
		this.activeTournament = this.tournaments[0];
	}

	async getAvailableTournaments() {
		return await Promise.all(
			this.tournaments.map(async (tournamentId) => {
				return await this.getTourney(tournamentId);
			})
		);
	}

	getActiveTournament() {
		return this.activeTournament;
	}

	setActiveTournament(tournamentId: string) {
		if (this.tournaments.includes(tournamentId)) {
			this.activeTournament = tournamentId;
		} else {
			throw new Error(`Tournament ID ${tournamentId} is not available.`);
		}
	}

	async getTourney(id: string = this.activeTournament) {
		const { data, error } = await this.client.GET('/v1/tournaments/{tournamentID}', {
			params: {
				path: {
					tournamentID: id
				},
				header: {
					'x-api-key': this.apiKey,
					'x-api-user-id': this.userId
				}
			}
		});

		if (data !== undefined) {
			return data;
		} else {
			return error;
		}
	}

	async getPlayers() {
		const { data, error } = await this.client.GET('/v1/tournaments/{tournamentID}/players', {
			params: {
				path: {
					tournamentID: this.activeTournament
				},
				header: {
					'x-api-key': this.apiKey,
					'x-api-user-id': this.userId
				}
			}
		});

		if (data !== undefined) {
			return data;
		} else {
			return error;
		}
	}

  async getGames () {
    const throttledGetGames = pThrottle({
      limit: 1,
      interval: 10000
    })(this.getGamesInternal.bind(this));
    return await throttledGetGames();
  }

	private async getGamesInternal() {
		const { data, error } = await this.client.GET('/v1/tournaments/{tournamentID}/games', {
			params: {
				path: {
					tournamentID: this.activeTournament
				},
				header: {
					'x-api-key': this.apiKey,
					'x-api-user-id': this.userId
				}
			}
		});

		if (data !== undefined) {
			return data;
		} else {
			return error;
		}
	}

	async getMatchInfo(gameID: string) {
		const { data, error } = await this.client.GET('/v1/tournaments/{tournamentID}/games/{gameID}', {
			params: {
				path: {
					tournamentID: this.activeTournament,
					gameID
				},
				header: {
					'x-api-key': this.apiKey,
					'x-api-user-id': this.userId
				}
			}
		});

		if (data !== undefined) {
			return data;
		} else {
			return error;
		}
	}

	async getPlayer(playerID: string) {
		const { data, error } = await this.client.GET(
			'/v1/tournaments/{tournamentID}/players/{playerID}',
			{
				params: {
					path: {
						tournamentID: this.activeTournament,
						playerID
					},
					header: {
						'x-api-key': this.apiKey,
						'x-api-user-id': this.userId
					}
				}
			}
		);

		if (data !== undefined) {
			return data;
		} else {
			return error;
		}
	}

	async declareWinner(
		gameId: string,
		who: 0 | 1,
		result: 'KO' | 'TO' | 'JD' | 'TKO' | 'HLD' | 'BY' | 'DQ' | 'FF' | 'T',
		tournamentId: string = this.activeTournament
	) {
		console.log(gameId);
		const { error } = await this.client.POST('/v1/tournaments/{tournamentID}/games/{gameID}', {
			params: {
				path: {
					tournamentID: tournamentId,
					gameID: gameId
				},
				header: {
					'x-api-key': this.apiKey,
					'x-api-user-id': this.userId
				}
			},
			body: {
				state: 'active',
				slots: [
					{ score: 1 - who, checkIn: 'not_ready' },
					{ score: who, checkIn: 'not_ready' }
				],
				locationID: null,
				resultAnnotation: result
			}
		});
		if (error !== undefined) {
			console.error(error);
		}
	}
}

interface apiError {
	message: string;
	code: string;
	issues?: {
		message: string;
	}[];
}

function isApiError(response: any | apiError): response is apiError {
	if ((response as apiError).issues) {
		return true;
	}
	return false;
}

export { TrueFinals, isApiError };
